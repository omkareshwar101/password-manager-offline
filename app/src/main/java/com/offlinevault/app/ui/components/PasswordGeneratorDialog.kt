@Composable
fun PasswordGeneratorDialog(
    container: AppContainer,
    onDismiss: () -> Unit,
    onUsePassword: (String) -> Unit,
) {
    var length by remember { mutableIntStateOf(16) }
    var uppercase by remember { mutableStateOf(true) }
    var lowercase by remember { mutableStateOf(true) }
    var digits by remember { mutableStateOf(true) }
    var symbols by remember { mutableStateOf(true) }
    var excludeAmbiguous by remember { mutableStateOf(false) }
    var generated by remember { mutableStateOf("") }
    var refreshSeed by remember { mutableIntStateOf(0) }
    val generator = remember { PasswordGenerator() }
    val anySelected = uppercase || lowercase || digits || symbols
    val copy = rememberCopyMessage(container)

    LaunchedEffect(
        length,
        uppercase,
        lowercase,
        digits,
        symbols,
        excludeAmbiguous,
        refreshSeed,
    ) {
        generated = if (anySelected) {
            generator.generate(
                PasswordOptions(
                    length = length,
                    uppercase = uppercase,
                    lowercase = lowercase,
                    digits = digits,
                    symbols = symbols,
                    excludeAmbiguous = excludeAmbiguous,
                ),
            )
        } else {
            ""
        }
    }

    AlertDialog(
        onDismissRequest = onDismiss,
        title = { Text(stringResource(R.string.password_generator)) },
        text = {
            Column(
                modifier = Modifier
                    .fillMaxWidth()
                    .verticalScroll(rememberScrollState()),
                verticalArrangement = Arrangement.spacedBy(10.dp),
            ) {
                Surface(
                    shape = MaterialTheme.shapes.medium,
                    color = MaterialTheme.colorScheme.primaryContainer,
                ) {
                    Row(
                        modifier = Modifier
                            .fillMaxWidth()
                            .padding(start = 14.dp, top = 10.dp, bottom = 10.dp, end = 4.dp),
                        verticalAlignment = Alignment.CenterVertically,
                    ) {
                        Text(
                            text = generated.ifEmpty { "—" },
                            fontFamily = FontFamily.Monospace,
                            fontWeight = FontWeight.SemiBold,
                            color = MaterialTheme.colorScheme.onPrimaryContainer,
                            modifier = Modifier.weight(1f),
                        )
                        IconButton(
                            onClick = { copy(generated) },
                            enabled = generated.isNotBlank(),
                        ) {
                            Icon(
                                imageVector = Icons.Outlined.ContentCopy,
                                contentDescription = stringResource(R.string.copy),
                            )
                        }
                        IconButton(
                            onClick = { refreshSeed++ },
                            enabled = anySelected,
                        ) {
                            Icon(
                                imageVector = Icons.Outlined.Refresh,
                                contentDescription = stringResource(R.string.regenerate),
                            )
                        }
                    }
                }

                PasswordStrengthMeter(password = generated)

                Text(
                    text = stringResource(R.string.length, length),
                    style = MaterialTheme.typography.labelLarge,
                )
                Slider(
                    value = length.toFloat(),
                    onValueChange = { length = it.toInt() },
                    valueRange = 8f..32f,
                    steps = 23,
                )

                ToggleRow(
                    label = stringResource(R.string.include_uppercase),
                    checked = uppercase,
                    onCheckedChange = { uppercase = it },
                )
                ToggleRow(
                    label = stringResource(R.string.include_lowercase),
                    checked = lowercase,
                    onCheckedChange = { lowercase = it },
                )
                ToggleRow(
                    label = stringResource(R.string.include_digits),
                    checked = digits,
                    onCheckedChange = { digits = it },
                )
                ToggleRow(
                    label = stringResource(R.string.include_symbols),
                    checked = symbols,
                    onCheckedChange = { symbols = it },
                )
                ToggleRow(
                    label = stringResource(R.string.exclude_ambiguous),
                    checked = excludeAmbiguous,
                    onCheckedChange = { excludeAmbiguous = it },
                )
                if (!anySelected) {
                    Text(
                        text = stringResource(R.string.include_at_least_one),
                        color = MaterialTheme.colorScheme.error,
                        style = MaterialTheme.typography.bodySmall,
                    )
                }
                Text(
                    text = stringResource(R.string.generator_note),
                    style = MaterialTheme.typography.bodySmall,
                    color = MaterialTheme.colorScheme.onSurfaceVariant,
                )
                Spacer(Modifier.height(2.dp))
                TextButton(
                    onClick = { refreshSeed++ },
                    modifier = Modifier.align(Alignment.CenterHorizontally),
                    enabled = anySelected,
                ) {
                    Text(stringResource(R.string.regenerate))
                }
            }
        },
        confirmButton = {
            TextButton(
                onClick = {
                    if (generated.isNotBlank()) {
                        onUsePassword(generated)
                        onDismiss()
                    }
                },
                enabled = generated.isNotBlank(),
            ) {
                Text(stringResource(R.string.use_this_password))
            }
        },
        dismissButton = {
            TextButton(onClick = onDismiss) {
                Text(stringResource(R.string.cancel))
            }
        },
    )
}

@Composable
private fun ToggleRow(
    label: String,
    checked: Boolean,
    onCheckedChange: (Boolean) -> Unit,
) {
    Row(
        modifier = Modifier.fillMaxWidth(),
        verticalAlignment = Alignment.CenterVertically,
        horizontalArrangement = Arrangement.spacedBy(4.dp),
    ) {
        Checkbox(checked = checked, onCheckedChange = onCheckedChange)
        Text(
            text = label,
            style = MaterialTheme.typography.bodyMedium,
            textAlign = TextAlign.Start,
        )
    }
}
